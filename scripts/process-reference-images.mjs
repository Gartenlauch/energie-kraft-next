import { readdir, mkdir, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { parseReferenceFilename, slugify, uniqueOutputStem } from "./reference-image-lib.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const source = path.join(root, "design-input", "reference-originals");
const output = path.join(root, "public", "images", "references");
const manifestPath = path.join(root, "src", "generated", "reference-projects.generated.ts");
const capacityFormat = new Intl.NumberFormat("de-DE", { maximumFractionDigits: 3 });
const isRaster = (filename) => /\.(jpe?g|png|webp|tiff?)$/i.test(filename);
const compare = (a, b) => a.localeCompare(b, "de", { numeric: true });
const folders = (await readdir(source, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort(compare);
const groups = [];
const skipped = [];
const samples = [];
let sourceCount = 0;
let parsedCount = 0;
let convertedCount = 0;

for (const groupName of folders) {
  const groupSlug = slugify(groupName);
  const folder = path.join(source, groupName);
  const files = (await readdir(folder, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && isRaster(entry.name))
    .map((entry) => entry.name).sort(compare);
  sourceCount += files.length;
  const used = new Map();
  const projects = [];
  for (const filename of files) {
    const parsed = parseReferenceFilename(filename, groupName);
    if (parsed.error) {
      skipped.push({ file: `${groupName}/${filename}`, reason: parsed.error });
      continue;
    }
    parsedCount += 1;
    const inputPath = path.join(folder, filename);
    const base = `${parsed.customerType.toLowerCase()}-${String(parsed.capacityKwp).replace(".", "-")}-kwp-${slugify(parsed.actualLocation)}`;
    const id = uniqueOutputStem(base, used);
    const image = `/images/references/${groupSlug}/${id}.webp`;
    const target = path.join(output, groupSlug, `${id}.webp`);
    try {
      await mkdir(path.dirname(target), { recursive: true });
      const info = await sharp(inputPath).rotate().resize({ width: 2400, height: 2400, fit: "inside", withoutEnlargement: true })
        .webp({ quality: 84 }).toFile(target);
      const before = (await stat(inputPath)).size;
      if (samples.length < 5) samples.push({ file: `${groupName}/${filename}`, before, after: info.size });
      convertedCount += 1;
      projects.push({
        id: `${groupSlug}-${id}`,
        group: groupSlug,
        actualLocation: parsed.actualLocation,
        customerType: parsed.customerType,
        capacityKwp: parsed.capacityKwp,
        image,
        width: info.width,
        height: info.height,
        alt: `Photovoltaikanlage in ${parsed.actualLocation} mit ${capacityFormat.format(parsed.capacityKwp)} kWp, ${parsed.customerType === "Gewerbe" ? "Gewerbeanlage" : "Privatanlage"}`,
      });
    } catch {
      skipped.push({ file: `${groupName}/${filename}`, reason: "image conversion failed" });
    }
  }
  if (projects.length) {
    const overview = [...projects].sort((a, b) => {
      const landscape = Number(b.width >= b.height) - Number(a.width >= a.height);
      return landscape || b.width * b.height - a.width * a.height || compare(a.id, b.id);
    })[0];
    groups.push({ groupName: groupName === "Kirchanschoering" ? "Kirchanschöring" : groupName,
      groupSlug, overviewImage: overview.image, projects });
  }
}
await mkdir(path.dirname(manifestPath), { recursive: true });
await writeFile(manifestPath,
  `// Generated by npm run images:references. Do not edit by hand.\nexport const referenceGroups = ${JSON.stringify(groups, null, 2)} as const;\n`,
  "utf8");
console.log(JSON.stringify({ sourceFolders: folders.length, sourceImages: sourceCount,
  parsed: parsedCount, converted: convertedCount, skipped, samples,
  output: path.relative(root, output), manifest: path.relative(root, manifestPath) }, null, 2));
